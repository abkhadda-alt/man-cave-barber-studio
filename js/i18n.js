window.MC_LANG = (function () {
  const supported = ["fr", "en", "es"];
  let lang = "fr";
  try {
    const saved = localStorage.getItem("mc-lang");
    if (supported.includes(saved)) lang = saved;
  } catch (e) {}
  const listeners = [];

  function t(key) {
    return (window.MC_I18N[lang] && window.MC_I18N[lang][key]) || window.MC_I18N.fr[key] || key;
  }

  function apply() {
    document.documentElement.lang = lang;
    document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
    document.querySelectorAll("[data-i18n-ph]").forEach((el) => (el.placeholder = t(el.dataset.i18nPh)));
    document.querySelectorAll("[data-lang]").forEach((b) => b.setAttribute("aria-pressed", b.dataset.lang === lang));
    listeners.forEach((fn) => fn(lang));
  }

  function set(next) {
    if (!supported.includes(next)) return;
    lang = next;
    try { localStorage.setItem("mc-lang", lang); } catch (e) {}
    apply();
  }

  document.addEventListener("click", (e) => {
    const btn = e.target.closest("[data-lang]");
    if (btn) set(btn.dataset.lang);
  });

  return { t, set, apply, get: () => lang, onChange: (fn) => listeners.push(fn) };
})();
